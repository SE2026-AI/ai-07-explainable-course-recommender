-- curricula: Khung chương trình đào tạo: một phiên bản của một ngành, áp dụng cho một dải khóa
CREATE TABLE curricula (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	code VARCHAR(50) NOT NULL, 
	major_id INTEGER NOT NULL, 
	name TEXT NOT NULL, 
	name_en TEXT, 
	program_type VARCHAR(30) NOT NULL, 
	effective_from_cohort INTEGER NOT NULL, 
	effective_to_cohort INTEGER, 
	total_credits INTEGER NOT NULL, 
	standard_semesters INTEGER NOT NULL, 
	max_credits_per_term INTEGER NOT NULL, 
	grading_scheme_id INTEGER NOT NULL, 
	source_id INTEGER, 
	status VARCHAR(20) NOT NULL, 
	CONSTRAINT pk_curricula PRIMARY KEY (id), 
	CONSTRAINT ck_curricula_status CHECK (status IN ('draft', 'active', 'retired')), 
	CONSTRAINT ck_curricula_positive CHECK (total_credits > 0 AND standard_semesters > 0), 
	CONSTRAINT ck_curricula_cohort_range CHECK (effective_to_cohort IS NULL OR effective_to_cohort >= effective_from_cohort), 
	CONSTRAINT uq_curricula_code UNIQUE (code), 
	CONSTRAINT fk_curricula_major_id_majors FOREIGN KEY(major_id) REFERENCES majors (id) ON DELETE RESTRICT, 
	CONSTRAINT fk_curricula_grading_scheme_id_grading_schemes FOREIGN KEY(grading_scheme_id) REFERENCES grading_schemes (id) ON DELETE RESTRICT, 
	CONSTRAINT fk_curricula_source_id_data_sources FOREIGN KEY(source_id) REFERENCES data_sources (id) ON DELETE RESTRICT
);

CREATE INDEX ix_curricula_grading_scheme_id ON curricula (grading_scheme_id);
CREATE INDEX ix_curricula_major_id ON curricula (major_id);
CREATE INDEX ix_curricula_source_id ON curricula (source_id);

