CREATE TABLE app_settings (
	key VARCHAR(50) NOT NULL, 
	value TEXT NOT NULL, 
	note TEXT, 
	CONSTRAINT pk_app_settings PRIMARY KEY (key)
);


-- data_sources: Văn bản/nguồn mà dữ liệu được lấy ra; mọi dữ liệu tham chiếu đều truy được về đây
CREATE TABLE data_sources (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	code VARCHAR(50) NOT NULL, 
	title TEXT NOT NULL, 
	document_number VARCHAR(50), 
	issued_date DATE, 
	issuer TEXT, 
	file_name TEXT, 
	note TEXT, 
	CONSTRAINT pk_data_sources PRIMARY KEY (id), 
	CONSTRAINT uq_data_sources_code UNIQUE (code)
);


-- skills: Kỹ năng mà học phần rèn luyện (danh mục do nhóm tự gán)
CREATE TABLE skills (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	code VARCHAR(50) NOT NULL, 
	name TEXT NOT NULL, 
	CONSTRAINT pk_skills PRIMARY KEY (id), 
	CONSTRAINT uq_skills_code UNIQUE (code)
);


-- topics: Chủ đề học phần; dùng để nhóm các môn liên quan và cho sinh viên khai sở thích
CREATE TABLE topics (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	code VARCHAR(50) NOT NULL, 
	name TEXT NOT NULL, 
	CONSTRAINT pk_topics PRIMARY KEY (id), 
	CONSTRAINT uq_topics_code UNIQUE (code)
);


-- universities: Trường đại học. Mỗi trường độc lập: có ngành, học phần, thang điểm, lịch học kỳ riêng
CREATE TABLE universities (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	code VARCHAR(20) NOT NULL, 
	name TEXT NOT NULL, 
	name_en TEXT, 
	short_name VARCHAR(50), 
	is_demo BOOLEAN DEFAULT false NOT NULL, 
	CONSTRAINT pk_universities PRIMARY KEY (id), 
	CONSTRAINT uq_universities_code UNIQUE (code)
);


CREATE TABLE academic_years (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	university_id INTEGER NOT NULL, 
	code VARCHAR(20) NOT NULL, 
	start_year INTEGER NOT NULL, 
	CONSTRAINT pk_academic_years PRIMARY KEY (id), 
	CONSTRAINT uq_academic_years_university_id_code UNIQUE (university_id, code), 
	CONSTRAINT fk_academic_years_university_id_universities FOREIGN KEY(university_id) REFERENCES universities (id) ON DELETE RESTRICT
);

CREATE INDEX ix_academic_years_university_id ON academic_years (university_id);

-- courses: Học phần của một trường, dùng chung cho mọi CTĐT của trường đó
CREATE TABLE courses (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	university_id INTEGER NOT NULL, 
	code VARCHAR(20) NOT NULL, 
	name TEXT NOT NULL, 
	name_en TEXT, 
	credits INTEGER NOT NULL, 
	lecture_hours INTEGER, 
	practice_hours INTEGER, 
	self_study_hours INTEGER, 
	teaching_language VARCHAR(5) DEFAULT 'vi' NOT NULL, 
	CONSTRAINT pk_courses PRIMARY KEY (id), 
	CONSTRAINT uq_courses_university_id_code UNIQUE (university_id, code), 
	CONSTRAINT ck_courses_credits CHECK (credits > 0), 
	CONSTRAINT fk_courses_university_id_universities FOREIGN KEY(university_id) REFERENCES universities (id) ON DELETE RESTRICT
);

CREATE INDEX ix_courses_university_id ON courses (university_id);

-- data_issues: Chỗ văn bản gốc mâu thuẫn hoặc thiếu; ghi lại thay vì âm thầm sửa
CREATE TABLE data_issues (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	source_id INTEGER NOT NULL, 
	entity_type VARCHAR(50) NOT NULL, 
	entity_key VARCHAR(100) NOT NULL, 
	issue_type VARCHAR(50) NOT NULL, 
	description TEXT NOT NULL, 
	status VARCHAR(20) NOT NULL, 
	CONSTRAINT pk_data_issues PRIMARY KEY (id), 
	CONSTRAINT ck_data_issues_status CHECK (status IN ('open', 'resolved_in_data', 'closed')), 
	CONSTRAINT fk_data_issues_source_id_data_sources FOREIGN KEY(source_id) REFERENCES data_sources (id) ON DELETE RESTRICT
);

CREATE INDEX ix_data_issues_source_id ON data_issues (source_id);

CREATE TABLE faculties (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	university_id INTEGER NOT NULL, 
	code VARCHAR(20) NOT NULL, 
	name TEXT NOT NULL, 
	name_en TEXT, 
	CONSTRAINT pk_faculties PRIMARY KEY (id), 
	CONSTRAINT uq_faculties_university_id_code UNIQUE (university_id, code), 
	CONSTRAINT fk_faculties_university_id_universities FOREIGN KEY(university_id) REFERENCES universities (id) ON DELETE RESTRICT
);

CREATE INDEX ix_faculties_university_id ON faculties (university_id);

CREATE TABLE grading_schemes (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	university_id INTEGER NOT NULL, 
	code VARCHAR(30) NOT NULL, 
	name TEXT NOT NULL, 
	max_score NUMERIC(4, 2) NOT NULL, 
	pass_score NUMERIC(4, 2) NOT NULL, 
	source_id INTEGER, 
	CONSTRAINT pk_grading_schemes PRIMARY KEY (id), 
	CONSTRAINT ck_grading_schemes_pass_score CHECK (pass_score > 0 AND pass_score <= max_score), 
	CONSTRAINT fk_grading_schemes_university_id_universities FOREIGN KEY(university_id) REFERENCES universities (id) ON DELETE RESTRICT, 
	CONSTRAINT uq_grading_schemes_code UNIQUE (code), 
	CONSTRAINT fk_grading_schemes_source_id_data_sources FOREIGN KEY(source_id) REFERENCES data_sources (id) ON DELETE RESTRICT
);

CREATE INDEX ix_grading_schemes_source_id ON grading_schemes (source_id);
CREATE INDEX ix_grading_schemes_university_id ON grading_schemes (university_id);

-- students: Sinh viên. Khóa là id; (university_id, student_code) là khóa nghiệp vụ
CREATE TABLE students (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	university_id INTEGER NOT NULL, 
	student_code VARCHAR(30) NOT NULL, 
	full_name TEXT NOT NULL, 
	date_of_birth DATE, 
	email TEXT, 
	is_synthetic BOOLEAN DEFAULT false NOT NULL, 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL, 
	CONSTRAINT pk_students PRIMARY KEY (id), 
	CONSTRAINT uq_students_university_id_student_code UNIQUE (university_id, student_code), 
	CONSTRAINT fk_students_university_id_universities FOREIGN KEY(university_id) REFERENCES universities (id) ON DELETE RESTRICT
);

CREATE INDEX ix_students_university_id ON students (university_id);

-- course_equivalences: Học phần tương đương/thay thế
CREATE TABLE course_equivalences (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	course_id INTEGER NOT NULL, 
	equivalent_course_id INTEGER NOT NULL, 
	source_id INTEGER, 
	note TEXT, 
	CONSTRAINT pk_course_equivalences PRIMARY KEY (id), 
	CONSTRAINT uq_course_equivalences_course_id_equivalent_course_id UNIQUE (course_id, equivalent_course_id), 
	CONSTRAINT ck_course_equivalences_not_self CHECK (course_id <> equivalent_course_id), 
	CONSTRAINT fk_course_equivalences_course_id_courses FOREIGN KEY(course_id) REFERENCES courses (id) ON DELETE RESTRICT, 
	CONSTRAINT fk_course_equivalences_equivalent_course_id_courses FOREIGN KEY(equivalent_course_id) REFERENCES courses (id) ON DELETE RESTRICT, 
	CONSTRAINT fk_course_equivalences_source_id_data_sources FOREIGN KEY(source_id) REFERENCES data_sources (id) ON DELETE RESTRICT
);

CREATE INDEX ix_course_equivalences_course_id ON course_equivalences (course_id);
CREATE INDEX ix_course_equivalences_equivalent_course_id ON course_equivalences (equivalent_course_id);
CREATE INDEX ix_course_equivalences_source_id ON course_equivalences (source_id);

-- course_skills: Học phần rèn kỹ năng nào, mức độ (weight)
CREATE TABLE course_skills (
	course_id INTEGER NOT NULL, 
	skill_id INTEGER NOT NULL, 
	weight NUMERIC(4, 2) DEFAULT '1' NOT NULL, 
	CONSTRAINT pk_course_skills PRIMARY KEY (course_id, skill_id), 
	CONSTRAINT ck_course_skills_weight CHECK (weight > 0), 
	CONSTRAINT fk_course_skills_course_id_courses FOREIGN KEY(course_id) REFERENCES courses (id) ON DELETE CASCADE, 
	CONSTRAINT fk_course_skills_skill_id_skills FOREIGN KEY(skill_id) REFERENCES skills (id)
);

CREATE INDEX ix_course_skills_skill_id ON course_skills (skill_id);

-- course_topics: Học phần thuộc chủ đề nào; mỗi học phần có đúng một chủ đề chính
CREATE TABLE course_topics (
	course_id INTEGER NOT NULL, 
	topic_id INTEGER NOT NULL, 
	is_primary BOOLEAN DEFAULT false NOT NULL, 
	CONSTRAINT pk_course_topics PRIMARY KEY (course_id, topic_id), 
	CONSTRAINT fk_course_topics_course_id_courses FOREIGN KEY(course_id) REFERENCES courses (id) ON DELETE CASCADE, 
	CONSTRAINT fk_course_topics_topic_id_topics FOREIGN KEY(topic_id) REFERENCES topics (id)
);

CREATE INDEX ix_course_topics_topic_id ON course_topics (topic_id);
CREATE UNIQUE INDEX uq_course_topics_one_primary ON course_topics (course_id) WHERE is_primary;

CREATE TABLE grade_conversions (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	grading_scheme_id INTEGER NOT NULL, 
